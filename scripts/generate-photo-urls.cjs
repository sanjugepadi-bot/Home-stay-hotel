// Generates src/lib/photo-urls.ts: a stable public URL (/images/...) for every photo key, used by structured data
// and the sitemap. (The bundler's own import URLs contain a content hash that changes on every deploy.)
// Usage: node scripts/generate-photo-urls.cjs   (re-run after adding/removing photos in src/lib/photos.ts)
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const src = fs.readFileSync(path.join(root, "src/lib/photos.ts"), "utf8");
const imports = {};
for (const m of src.matchAll(/import (\w+) from "\.\.\/\.\.\/public\/([^"]+)";/g)) imports[m[1]] = "/" + m[2];
const block = src.match(/export const photos = \{([\s\S]*?)\} as const;/);
if (!block) throw new Error("photos object not found");
const keys = [...block[1].matchAll(/^\s*(\w+),?\s*$/gm)].map((m) => m[1]);
const missing = keys.filter((k) => !imports[k]);
if (missing.length) throw new Error("no import for keys: " + missing.join(", "));
for (const k of keys) if (!fs.existsSync(path.join(root, "public", imports[k]))) throw new Error("file missing for " + k);
const lines = keys.map((k) => `  ${k}: "${imports[k]}",`).join("\n");
fs.writeFileSync(
  path.join(root, "src/lib/photo-urls.ts"),
  `// GENERATED by scripts/generate-photo-urls.cjs — do not edit by hand.\n// Stable public URLs for structured data and the sitemap.\nimport type { PhotoKey } from "@/lib/photos";\n\nexport const photoPublicPath: Record<PhotoKey, string> = {\n${lines}\n};\n`
);
console.log("wrote src/lib/photo-urls.ts with", keys.length, "photo URLs");
